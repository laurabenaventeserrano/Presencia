test('B5 termino el bloque con confirmación y los minutos quedan guardados', async ({ page }) => {
  await open(page)
  await startTimer(page, 25, 'Diseñar')
  await page.clock.runFor(10 * 60_000)
  await page.getByRole('button', { name: 'Terminar' }).click()
  const dialog = page.getByRole('dialog', { name: '¿Terminar este bloque?' })
  await expect(dialog).toBeVisible()
  await expectNoAxeViolations(page)
  await dialog.getByRole('button', { name: 'Seguir' }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: 'Terminar' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Terminar' }).click()
  await expect(page.getByLabel('¿Qué necesitas hacer hoy?')).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('presencia:v1') ?? '{}'))
  expect(saved.records).toHaveLength(1)
  expect(saved.records[0]).toMatchObject({ kind: 'focus', title: 'Diseñar' })
  // Diez minutos trabajados (más el segundo que corre el reloj mientras axe revisa el diálogo).
  expect(Math.round(saved.records[0].focusMs / 60_000)).toBe(10)
})

test('B7 con un bloque en marcha no se puede empezar otro', async ({ page }) => {
  await open(page)
  await startTimer(page, 25)
  await page.getByRole('button', { name: 'Hoy' }).click()
  await expect(page.getByRole('button', { name: 'Temporizador' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Respirar', exact: true })).toBeDisabled()
  await expect(page.getByText('Ya hay un bloque en marcha')).toBeVisible()
  await page.getByRole('button', { name: 'Ir al bloque' }).click()
  await expect(timeText(page)).toBeVisible()
})

