test('B10 Espacio pausa y reanuda, y Escape cierra el diálogo', async ({ page }) => {
  await open(page)
  await startTimer(page, 25)
  await page.locator('body').click({ position: { x: 5, y: 400 } })
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Reanudar' })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Pausar' })).toBeVisible()
  await page.getByRole('button', { name: 'Terminar' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(timeText(page)).toBeVisible()
})

test('B11 el tiempo se anuncia cada minuto y al terminar, no cada segundo', async ({ page }) => {
  await open(page)
  await startTimer(page, 2)
  const live = page.locator('[aria-live="polite"]')
  await expect(live).toHaveText('Quedan 2 minutos')
  await page.clock.runFor(20_000)
  await expect(live).toHaveText('Quedan 2 minutos')
  await page.clock.runFor(41_000)
  await expect(live).toHaveText('Queda 1 minuto')
  await page.clock.runFor(60_000)
  await expect(live).toHaveText('Tiempo terminado')
})
