test('B2 veo la cuenta atrás y sigue correcta al recargar', async ({ page }) => {
  await open(page)
  await startTimer(page, 25, 'Escribir')
  await expect(timeText(page)).toHaveText('25:00')
  await page.clock.runFor(1000)
  await expect(timeText(page)).toHaveText('24:59')
  await page.clock.runFor(60_000)
  await expect(timeText(page)).toHaveText('23:59')
  await page.reload()
  await expect(timeText(page)).toHaveText('23:59')
  await page.clock.runFor(60_000)
  await expect(timeText(page)).toHaveText('22:59')
})

