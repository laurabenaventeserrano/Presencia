import { expect, test } from '@playwright/test'
import { expectNoAxeViolations, open, startTimer, timeText } from './helpers'

test('B1 activo el temporizador sin el chat', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'Temporizador' }).click()
  await expectNoAxeViolations(page)
  await page.getByRole('button', { name: '15 min' }).click()
  await page.getByLabel('Título (opcional)').fill('Leer el informe')
  await page.getByRole('button', { name: 'Play' }).click()
  await expect(page.getByRole('heading', { name: 'Leer el informe' })).toBeVisible()
  await expect(timeText(page)).toHaveText('15:00')
  await expectNoAxeViolations(page)
})

